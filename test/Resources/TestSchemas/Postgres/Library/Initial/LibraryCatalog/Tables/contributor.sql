CREATE TABLE library_catalog.contributor
(
    contributor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL DEFAULT '',
    disambiguation varchar(100) NOT NULL DEFAULT '',
    birth_year smallint,
    death_year smallint,
    full_name varchar(200) GENERATED ALWAYS AS
        (CASE WHEN last_name <> '' THEN first_name || ' ' || last_name ELSE first_name END) STORED,
    sortable_name varchar(200) GENERATED ALWAYS AS
        (CASE WHEN last_name <> '' THEN last_name || ', ' || first_name ELSE first_name END) STORED,
    CONSTRAINT uc_contributor UNIQUE (first_name, last_name, disambiguation)
);
CREATE INDEX idx_contributor_sortable_name ON library_catalog.contributor (sortable_name);
