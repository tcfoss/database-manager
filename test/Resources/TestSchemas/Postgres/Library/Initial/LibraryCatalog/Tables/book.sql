CREATE TABLE library_catalog.book
(
    book_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    subtitle varchar(100),
    description text,
    publication_year smallint,
    publisher varchar(100),
    acquisition_cost numeric(10, 2) NOT NULL DEFAULT 0.00,
    acquisition_date date,
    isbn varchar(20),
    full_title varchar(400) GENERATED ALWAYS AS
        (coalesce(title || ': ' || subtitle, title)
         || CASE WHEN publication_year IS NULL THEN '' ELSE ' (' || publication_year::text || ')' END) STORED
);
