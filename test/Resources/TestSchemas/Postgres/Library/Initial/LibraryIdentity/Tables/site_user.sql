CREATE TABLE library_identity.site_user
(
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patron_id integer,
    employee_id integer,
    password_hash varchar(100) COLLATE "C" NOT NULL,
    email varchar(100) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT TRUE,
    registration_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login timestamp,
    CONSTRAINT chk_site_user_one_of_patron_or_employee
        CHECK (patron_id IS NOT NULL OR employee_id IS NOT NULL),
    CONSTRAINT fk_site_user_patron FOREIGN KEY (patron_id) REFERENCES library_identity.patron (patron_id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_user_employee FOREIGN KEY (employee_id) REFERENCES library_identity.employee (employee_id) ON DELETE RESTRICT
);
CREATE INDEX idx_site_user_patron_id ON library_identity.site_user (patron_id);
CREATE INDEX idx_site_user_employee_id ON library_identity.site_user (employee_id);
