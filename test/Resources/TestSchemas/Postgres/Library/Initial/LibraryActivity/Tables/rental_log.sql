CREATE TABLE library_activity.rental_log
(
    log_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id integer NOT NULL,
    book_id integer NOT NULL REFERENCES library_catalog.book (book_id) ON DELETE RESTRICT,
    patron_id integer NOT NULL REFERENCES library_identity.patron (patron_id) ON DELETE RESTRICT,
    rental_date timestamp NOT NULL,
    due_date timestamp NOT NULL,
    return_date timestamp,
    fees_charged numeric(10, 2) NOT NULL DEFAULT 0.00,
    fees_paid numeric(10, 2) NOT NULL DEFAULT 0.00,
    notes text,
    log_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rental_log_rental_id ON library_activity.rental_log (rental_id);
CREATE INDEX idx_rental_log_book_id ON library_activity.rental_log (book_id);
CREATE INDEX idx_rental_log_patron_id ON library_activity.rental_log (patron_id);
