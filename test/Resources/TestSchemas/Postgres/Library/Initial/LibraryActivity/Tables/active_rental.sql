CREATE TABLE library_activity.active_rental
(
    rental_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL,
    patron_id integer NOT NULL,
    rental_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '14 days'),
    return_date timestamp,
    fees_charged numeric(10, 2) NOT NULL DEFAULT 0.00,
    fees_paid numeric(10, 2) NOT NULL DEFAULT 0.00,
    notes text,
    really_active char(1) GENERATED ALWAYS AS
        (CASE WHEN return_date IS NULL THEN 'Y'::char(1) ELSE NULL END) STORED,
    CONSTRAINT uc_active_rental_book_id UNIQUE (book_id, really_active),
    CONSTRAINT fk_active_rental_book FOREIGN KEY (book_id) REFERENCES library_catalog.book (book_id) ON DELETE RESTRICT,
    CONSTRAINT fk_active_rental_patron FOREIGN KEY (patron_id) REFERENCES library_identity.patron (patron_id) ON DELETE RESTRICT
);
CREATE INDEX idx_active_rental_patron_id ON library_activity.active_rental (patron_id);

COMMENT ON COLUMN library_activity.active_rental.really_active
    IS 'If null, the book is available to loan but cannot be deleted until fees are paid.';
