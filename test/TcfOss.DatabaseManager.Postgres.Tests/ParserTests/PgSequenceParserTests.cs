    [Theory]
    [InlineData("CREATE SEQUENCE ids OWNED BY app.items.id", "app.items")]
    [InlineData("CREATE SEQUENCE ids OWNED BY NONE", "")]
    [InlineData("ALTER SEQUENCE app.ids OWNED BY app.items.id", "app.ids,app.items")]
    [InlineData("ALTER SEQUENCE ids OWNER TO owner_name", "ids")]
    [InlineData("ALTER SEQUENCE ids RENAME TO new_ids", "ids")]
    [InlineData("ALTER SEQUENCE ids SET SCHEMA archive", "ids")]
    [InlineData("DROP SEQUENCE app.ids, other_ids CASCADE", "app.ids,other_ids")]
    [InlineData("ALTER TABLE app.items ALTER id RESTART", "app.items")]
    public void SequenceReferences_ReportExistingTargetsAndOwnedTable(string sql, string expected)
    {
        var statement = Assert.IsType<Statement>(ParseStatement(sql), exactMatch: false);
        var context = new ReferencedItemsManager { Filters = ObjectNameFilters.All };
        context.AddLocalVariable(new Identifier("ids"));
        using var scope = context.Enter(ReferencedItemsContext.SelectItem);

        var references = statement.GetReferencedItems(context).OfType<ItemRef.ObjectNameRef>().ToArray();

        Assert.Equal(expected, string.Join(',', references.Select(reference => reference.Name.ToSql())));
        Assert.Equal(ReferencedItemsContext.SelectItem, context.CurrentContext);
        Assert.Empty(statement.GetReferencedItems(new ReferencedItemsManager { Filters = ObjectNameFilters.None }));
        _ = statement.GetReferencedItems(context).Take(1).ToArray();
        Assert.Equal(ReferencedItemsContext.SelectItem, context.CurrentContext);
    }

    [Fact]
    public void SequenceDeclarations_PreserveSourcesCommentsAndStatementBoundaries()
    {
        const string sql = "/* lead */ CREATE TEMPORARY SEQUENCE IF NOT EXISTS \"Ids\" START WITH 10 OWNED BY app.items.\"Id\" /* tail */; ALTER SEQUENCE \"Ids\" OWNER TO \"Owner\"; ALTER TABLE app.items ALTER COLUMN \"Id\" SET GENERATED ALWAYS; SELECT 1";
        var statements = ParseStatements(sql, sourceId: 163);
        var create = Assert.IsType<CreateSequence>(statements[0]);
        var alter = Assert.IsType<AlterSequence>(statements[1]);
        var table = Assert.IsType<AlterTable>(statements[2]);

        Assert.Equal(4, statements.Count);
        Assert.Equal(0, create.Meta.Start);
        Assert.Equal(sql.IndexOf(';') + 1, create.Meta.EndPlusTerminatorLength);
        Assert.Equal("TEMPORARY", create.TemporaryLabel!.ToSql());
        Assert.True(create.IfNotExists);
        Assert.All(create.Name.Values, identifier => Assert.Equal(163, identifier.Source!.Value.SourceId));
        var start = Assert.IsType<PgStatementSequenceOption.Start>(create.Options[0]);
        Assert.Equal(10, start.Value);
        Assert.True(start.UseWith);
        var ownedBy = Assert.IsType<PgStatementSequenceOption.OwnedBy>(create.Options[1]);
        Assert.All(ownedBy.Column!.Values, identifier => Assert.Equal(163, identifier.Source!.Value.SourceId));
        Assert.Equal(163, Assert.Single(alter.Name.Values).Source!.Value.SourceId);
        var owner = Assert.IsType<Account.Identity>(Assert.IsType<PgAlterSequenceOperation.OwnerTo>(alter.Operation).Owner);
        Assert.Equal(163, owner.Name.Source!.Value.SourceId);
        var identity = Assert.IsType<AlterTableOperation.PgIdentity>(Assert.Single(table.Operations));
        Assert.Equal(163, identity.Column.Source!.Value.SourceId);
        Assert.Contains(create.Meta.PreNonSql!, trivia => trivia is NonSql.BlockComment { Body: " lead " });
        Assert.Contains(create.Meta.PostNonSql!, trivia => trivia is NonSql.BlockComment { Body: " tail " });
        Assert.IsType<Select>(statements[3]);
        using var formatter = Helpers.CreateFormatter();
        string formatted = formatter.GetFormatted(sql);
        Assert.Equal(formatted, formatter.GetFormatted(formatted));
    }

