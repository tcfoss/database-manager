"""Tools for writing C# code."""

from typing import TextIO

_HEADER = """// <auto-generated>See tools under tools/dbman-dev</auto-generated>
#nullable enable
"""


class CsWriter:
    """Helper class for writing C# code to a text stream."""

    def __init__(self, stream: TextIO):
        self._stream = stream
        self._indent_level = 0

    def indent(self):
        self._indent_level += 1

    def dedent(self):
        if self._indent_level > 0:
            self._indent_level -= 1

    def _write_indent(self):
        self._stream.write("    " * self._indent_level)

    def write_header(self):
        """Write the auto-generated header to the C# code stream."""
        self._stream.write(_HEADER + "\n")

    def write_blank(self):
        """Write a blank line to the C# code stream."""
        self._stream.write("\n")

    def write_line(self, line: str = ""):
        """Write a line to the C# code stream."""
        self._write_indent()
        self._stream.write(line + "\n")

    def write_hanging_indent(self, lines: list[str]):
        """Write lines with a hanging indent."""
        if not lines:
            return
        self.write_line(lines[0])
        self.indent()
        for line in lines[1:]:
            self.write_line(line)
        self.dedent()

    def open_block(self):
        """Open a C# code block with braces."""
        self.write_line("{")
        self.indent()

    def close_block(self):
        """Close a C# code block with braces."""
        self.dedent()
        self.write_line("}")
