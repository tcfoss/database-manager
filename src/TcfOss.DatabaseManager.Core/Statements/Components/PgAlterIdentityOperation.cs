using TcfOss.DatabaseManager.Core.Formatting;
using TcfOss.DatabaseManager.Core.IO;

namespace TcfOss.DatabaseManager.Core.Statements.Components;

public abstract record PgAlterIdentityOperation : IWriteSql
{
    public abstract void ToSql(SqlTextWriter writer);

    public void FormatSql(SqlTextWriter writer, FormatManager manager)
    {
        ToSql(writer);
    }

    public record Add(StatementColumnOption.Generated.PgIdentity Identity) : PgAlterIdentityOperation
    {
        public override void ToSql(SqlTextWriter writer)
        {
            writer.WriteSql($"ADD {Identity}");
        }
    }

    public record SetGenerated(bool Always) : PgAlterIdentityOperation
    {
        public override void ToSql(SqlTextWriter writer)
        {
            writer.Write(Always ? "SET GENERATED ALWAYS" : "SET GENERATED BY DEFAULT");
        }
    }

    public record Drop(bool IfExists) : PgAlterIdentityOperation
    {
        public override void ToSql(SqlTextWriter writer)
        {
            writer.Write(IfExists ? "DROP IDENTITY IF EXISTS" : "DROP IDENTITY");
        }
    }

    public record SequenceOption(PgStatementSequenceOption Option) : PgAlterIdentityOperation
    {
        public override void ToSql(SqlTextWriter writer)
        {
            if (Option is not PgStatementSequenceOption.Restart)
            {
                writer.Write("SET ");
            }
            Option.ToSql(writer);
        }
    }
}
