using TcfOss.DatabaseManager.Core.BuiltIn;
using TcfOss.DatabaseManager.Core.Common;
using TcfOss.DatabaseManager.Core.Lexing.Tokens;
using TcfOss.DatabaseManager.Core.Parsing;
using TcfOss.DatabaseManager.Core.Statements.Components;

namespace TcfOss.DatabaseManager.Postgres.Parsing;

public class PgTableParser(Parser parser) : TableParser(parser)
{
    protected override StatementColumn.MsComputed? ParseOptionalComputedColumn(ParserState state, Identifier name)
    {
        return null;
    }

    public override StatementColumnOption? ParseNextColumnOption(ParserState state)
    {
        Token start = state.Peek();
        if (start is Word { Keyword: Keyword.AS or Keyword.IDENTITY })
        {
            throw ParserState.ExpectedException("GENERATED ALWAYS AS or GENERATED BY DEFAULT AS IDENTITY", start);
        }
        StatementColumnOption? option = base.ParseNextColumnOption(state);
        if (option is StatementColumnOption.Generated.AsExpression { StoredAsPersistent: true })
        {
            throw ParserState.ExpectedException("STORED or VIRTUAL", start);
        }
        return option;
    }
}
